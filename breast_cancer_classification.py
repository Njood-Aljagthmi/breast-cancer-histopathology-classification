def predict_uploaded_image(binary_model, benign_model, malignant_model):
    #
    # Creates an interactive widget for image upload and prediction
    #
    upload = widgets.FileUpload(accept='.png,.jpg,.jpeg', multiple=False)
    output = widgets.Output()

    def on_upload_change(change):
        with output:
            clear_output()
            if not upload.value:
                return

            # Read uploaded image
            uploaded_file = next(iter(upload.value.values()))
            img = Image.open(io.BytesIO(uploaded_file['content']))

            # Preprocess image
            img = img.resize((128, 128))
            img_array = np.array(img)
            img_array = cv2.cvtColor(img_array, cv2.COLOR_RGB2BGR)
            img_array = img_array / 255.0
            img_array = np.expand_dims(img_array, axis=0)

            # Make predictions
            binary_pred = binary_model.predict(img_array, verbose=0)
            binary_class = np.argmax(binary_pred)

            if binary_class == 0:  # Benign
                subtype_pred = benign_model.predict(img_array, verbose=0)
                subtype_class = np.argmax(subtype_pred)
                subtype_name = ['Adenosis', 'Fibroadenoma', 'Phyllodes Tumor', 'Tubular Adenoma'][subtype_class]
                result = f"Benign - {subtype_name} (Confidence: {binary_pred[0][binary_class]:.2f})"
