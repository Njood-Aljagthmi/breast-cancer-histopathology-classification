                subtype_pred = malignant_model.predict(img_array, verbose=0)
                subtype_class = np.argmax(subtype_pred)
                subtype_name = ['Ductal Carcinoma', 'Lobular Carcinoma',
                              'Mucinous Carcinoma', 'Papillary Carcinoma'][subtype_class]
