def evaluate_all_models(binary_model, benign_model, malignant_model, test_dataset, test_dataset_b, test_dataset_m):
    #
    # Evaluates all models and returns comprehensive metrics
    #
    # Binary model evaluation
    binary_true, binary_pred = [], []
    for images, labels in test_dataset:
        preds = binary_model.predict(images, verbose=0)
        binary_true.extend(np.argmax(labels.numpy(), axis=1))
        binary_pred.extend(np.argmax(preds, axis=1))

    binary_acc = accuracy_score(binary_true, binary_pred)

    # Benign model evaluation
    benign_true, benign_pred = [], []
    for images, labels in test_dataset_b:
        preds = benign_model.predict(images, verbose=0)
        benign_true.extend(np.argmax(labels.numpy(), axis=1))
        benign_pred.extend(np.argmax(preds, axis=1))

    benign_acc = accuracy_score(benign_true, benign_pred)

    # Malignant model evaluation
    malignant_true, malignant_pred = [], []
    for images, labels in test_dataset_m:
        preds = malignant_model.predict(images, verbose=0)
        malignant_true.extend(np.argmax(labels.numpy(), axis=1))
        malignant_pred.extend(np.argmax(preds, axis=1))

    malignant_acc = accuracy_score(malignant_true, malignant_pred)

    # Hierarchical evaluation
    hierarchical_acc = hierarchical_evaluation(binary_model, benign_model, malignant_model,
                                            test_dataset_b, test_dataset_m)

    return {
        'binary_accuracy': binary_acc,
        'benign_accuracy': benign_acc,
        'malignant_accuracy': malignant_acc,
        'hierarchical_accuracy': hierarchical_acc
    }

def hierarchical_evaluation(binary_model, benign_model, malignant_model, test_dataset_b, test_dataset_m):
    #
    # Evaluates the full hierarchical pipeline
    #
    correct = 0
    total = 0

    # Process benign cases
    for image, label in test_dataset_b.unbatch():
        img_array = np.expand_dims(image.numpy(), axis=0)

        # Binary prediction
        bin_pred = np.argmax(binary_model.predict(img_array, verbose=0))

        # Subtype prediction
        if bin_pred == 0:  # Correctly predicted as benign
            sub_pred = np.argmax(benign_model.predict(img_array, verbose=0))
            true_sub = np.argmax(label.numpy())
            if sub_pred == true_sub:
                correct += 1
        total += 1

    # Process malignant cases
    for image, label in test_dataset_m.unbatch():
        img_array = np.expand_dims(image.numpy(), axis=0)

        # Binary prediction
        bin_pred = np.argmax(binary_model.predict(img_array, verbose=0))

        # Subtype prediction
        if bin_pred == 1:  # Correctly predicted as malignant
            sub_pred = np.argmax(malignant_model.predict(img_array, verbose=0))
            true_sub = np.argmax(label.numpy())
            if sub_pred == true_sub:
                correct += 1
        total += 1

    return correct / total

